local meta = FindMetaTable("Player")
for k, v in pairs({
	Oddities = function(self)
		return self:GetNWInt("evilrp_oddities", 0)
	end,
	OddityList = function(self)
		local returns = { }
		for k, v in pairs(ODDITIES) do
			if self:HasOddity(k) then
				returns[#returns + 1] = v
			end
		end
		return returns
	end,
	HasOddity = function(self, oddity)
		return bit.Check(self:Oddities(), oddity)
	end,
	ClearOddities = function(self)
		return self:SetNWInt("evilrp_oddities", 0)
	end,
	AddOddity = function(self, oddity)
		if self:HasOddity(oddity) then
			return
		end
		local odds = bit.Set(self:Oddities(), oddity)
		self:SetNWInt("evilrp_oddities", odds)
		timer.Simple(1, function()
			return ODDITIES[oddity]:Inform(self)
		end)
		return odds
	end,
	RemoveOddity = function(self, oddity)
		if not self:HasOddity(oddity) then
			return
		end
		local odds = bit.Unset(self:Oddities(), oddity)
		self:SetNWInt("evilrp_oddities", odds)
		return odds
	end
}) do
	meta[k] = v
end
